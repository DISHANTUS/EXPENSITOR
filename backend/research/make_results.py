"""Run every evaluation and write the numbers to research/generated/results.json.

    docker compose exec api python -m research.make_results

This is the single source of truth for every number in the paper. The host-side
script paper/build_assets.py reads the JSON it writes and generates the LaTeX
tables and figures — so the paper's numbers are produced by this code over the
checked-in data, never hand-typed.

Deterministic by construction: the SMS/receipt evals are pure functions of their
datasets, and the reason eval is fixed-seed. The output carries no timestamp, so
re-running yields a byte-identical file (a reviewer can `git diff` it to zero).
"""

from __future__ import annotations

import asyncio
import json
import logging
from pathlib import Path

logging.disable(logging.INFO)

from research import eval_receipts, eval_reasons, eval_sms  # noqa: E402

_OUT = Path(__file__).parent / "generated" / "results.json"


def build() -> dict:
    return {
        "_about": (
            "Generated by `python -m research.make_results` over the checked-in "
            "seed datasets. Do not edit by hand. Numbers are on hand-labelled "
            "seed sets (SMS/receipts) and a fixed-seed synthetic history "
            "(reasons); see the paper's Limitations section."
        ),
        "sms": eval_sms.compute(),
        "receipts": eval_receipts.compute(),
        "reasons": asyncio.run(eval_reasons.compute()),
    }


def main() -> None:
    results = build()
    _OUT.parent.mkdir(parents=True, exist_ok=True)
    _OUT.write_text(json.dumps(results, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {_OUT}")
    print("  SMS      F1 = %.3f  (precision %.3f)" % (
        results["sms"]["detection"]["expensitor"]["f1"],
        results["sms"]["detection"]["expensitor"]["precision"]))
    print("  receipts line-item F1 = %.3f" % results["receipts"]["line_items"]["f1"])
    print("  reasons  Hit@1 = %.3f" % results["reasons"]["methods"]["Expensitor (amount-aware)"]["hit1"])
    print("\nNext (on the host, where matplotlib is installed):")
    print("  python paper/build_assets.py")


if __name__ == "__main__":
    main()
